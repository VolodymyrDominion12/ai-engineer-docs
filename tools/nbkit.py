"""Спільні хелпери для генераторів ноутбуків довідника «AI Engineer».

# Правила написання клітинок

Кожен модуль `tools/notebooks/nb_NN.py` тримає клітинки як рядкові літерали.
Python обробляє escape-послідовності **двічі**: спершу коли читає модуль,
потім коли виконує клітинку. Через це екранування легко втратити.

## 1. Керуючі символи

У модулі `"\\x00"` стає справжнім NUL-байтом у джерелі клітинки й ламає ядро
IPython. Так само `\\t`, `\\r` і `\\n` перетворюються на справжні символи й
псують вивід (наприклад, розривають таблицю).

**Правило:** якщо в тексті клітинки потрібен літеральний `\\n`, `\\r`, `\\t`
або `\\x00` — використовуйте **сирий рядок** (`r"..."`) або подвойте слеші.
Збирач перевіряє наявність керуючих символів і відхиляє такий модуль.

## 2. Колізія лапок

Рядок на кшталт `print('  \\'{"a": 1}\\'')` у модулі ламається. Не вкладайте
однакові лапки — замініть внутрішні на подвійні або змініть тип зовнішніх.

## 3. Потрійні лапки

Не вживайте ` ``` ` усередині клітинки з кодом: це передчасно закриває блок
розмітки в контексті, де код показується. Якщо потрійні лапки справді потрібні
в рядку — збудуйте їх як `chr(96) * 3`.

## 4. Побудова даних замість ручного екранування

Якщо клітинка містить JSON або інший структурований текст, **будуйте його
програмно** (`json.dumps`), а не вписуйте руками. Це усуває цілий клас помилок
з екрануванням лапок усередині рядків.

## 5. Затінення імен між клітинками

Усі клітинки виконуються в **спільному namespace** ядра. Ім'я, використане як
ціль циклу в одній клітинці й для об'єкта в іншій, тихо затирає об'єкт.
Перевірка: `python3 tools/build_notebooks.py --check-shadowing`.

## 6. Журнали замість посилань

Якщо збираєте історію викликів у список, зберігайте **знімок** (`list(...)`),
а не посилання на список, який ви дописуєте далі, — інакше всі записи
покажуть фінальний стан.
"""

from __future__ import annotations

import nbformat as nbf


def md(text: str) -> nbf.NotebookNode:
    """Markdown-клітинка. Провідні й прикінцеві порожні рядки обрізаються."""
    return nbf.v4.new_markdown_cell(text.strip("\n"))


def code(text: str) -> nbf.NotebookNode:
    """Кодова клітинка. Провідні й прикінцеві порожні рядки обрізаються."""
    return nbf.v4.new_code_cell(text.strip("\n"))


